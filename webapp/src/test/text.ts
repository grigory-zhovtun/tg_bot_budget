/** Ожидаемая строка с неразрывными пробелами, как у форматтеров: внутри чисел и
 * между числом и единицей («5 250 000», «460 $», «111 %», «23 613 075 сум»).
 * Для сравнения textContent; getByText и так сводит неразрывный пробел к обычному. */
export function nb(text: string): string {
  return text
    .replace(/(\d) (?=\d)/g, "$1\u00a0")
    .replace(/(\d) (?=[$₽%]|сум|[A-Z]{3}\b)/g, "$1\u00a0");
}
